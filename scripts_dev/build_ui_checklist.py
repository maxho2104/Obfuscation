PASS_FAIL = "□ ОК   □ НЕ ОК"


def _set_cell_shading(cell, hex_fill: str) -> None:
    """Заливает ячейку цветом."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def _repeat_header(row) -> None:
    """Повторяет строку заголовка на каждой странице."""
    tr_pr = row._tr.get_or_add_trPr()
    header = OxmlElement("w:tblHeader")
    header.set(qn("w:val"), "true")
    tr_pr.append(header)


def _forbid_row_split(row) -> None:
    """Не разрешает разрывать строку таблицы между страницами."""
    tr_pr = row._tr.get_or_add_trPr()
    cant_split = OxmlElement("w:cantSplit")
    tr_pr.append(cant_split)


def _style_run(run, size: int = 10, bold: bool = False) -> None:
    """Задаёт шрифт и размер текста внутри ячейки."""
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = "Calibri"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")


def _fill_cell(cell, text: str, *, bold: bool = False, size: int = 10,
               align=WD_ALIGN_PARAGRAPH.LEFT) -> None:
    """Записывает текст в ячейку с заданным оформлением."""
    cell.text = ""
    paragraph = cell.paragraphs[0]
    paragraph.alignment = align
    paragraph.paragraph_format.space_before = Pt(0)
    paragraph.paragraph_format.space_after = Pt(0)
    _style_run(paragraph.add_run(text), size=size, bold=bold)


def _fix_table_layout(table, widths) -> None:
    """Задаёт фиксированную разметку таблицы и ширины колонок сетки."""
    tbl_pr = table._tbl.tblPr
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tbl_pr.append(layout)
    tbl_w = OxmlElement("w:tblW")
    tbl_w.set(qn("w:type"), "dxa")
    tbl_w.set(qn("w:w"), str(sum(int(w.twips) for w in widths)))
    tbl_pr.append(tbl_w)
    for grid_col, width in zip(table._tbl.tblGrid.findall(qn("w:gridCol")), widths):
        grid_col.set(qn("w:w"), str(int(width.twips)))


def _make_table(document: Document, header: tuple[str, ...], widths) -> object:
    """Создаёт таблицу с заголовком и заданными ширинами колонок."""
    table = document.add_table(rows=1, cols=len(header))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    _fix_table_layout(table, widths)
    header_row = table.rows[0]
    _repeat_header(header_row)
    for index, (title, width) in enumerate(zip(header, widths)):
        cell = header_row.cells[index]
        cell.width = width
        _set_cell_shading(cell, HEADER_BG)
        _fill_cell(cell, title, bold=True)
    return table


def _add_check_row(table, number: str, check: str, expected: str, zebra: bool) -> None:
    """Добавляет строку проверки: номер, шаг, ожидание, отметки, комментарий."""
    row = table.add_row()
    _forbid_row_split(row)
    values = (number, check, expected, PASS_FAIL, "")
    for index, (cell, value) in enumerate(zip(row.cells, values)):
        cell.width = COLUMNS[index]
        if zebra:
            _set_cell_shading(cell, ZEBRA_BG)
        align = WD_ALIGN_PARAGRAPH.CENTER if index in (0, 3) else WD_ALIGN_PARAGRAPH.LEFT
        _fill_cell(cell, value, size=9, align=align)


